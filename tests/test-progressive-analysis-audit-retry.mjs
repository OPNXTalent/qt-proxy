import assert from 'node:assert/strict';
import { conceptNodes } from '../lib/concept-nodes-v1.js';
import { createContextPackets, validateArtifactCore, validateContextCompanion } from '../lib/interpretation-artifact.js';
const artifact = validateArtifactCore({ proposition: 'q', thesis: 'answer.', canonical_response: 'A sufficiently complete canonical answer.' }, { inquiryKey: 'server:test', revision: 1, query: 'q' });
const companion = validateContextCompanion({ interpretive_context: 'Useful additional context.', concept_node_ids: ['shamayim', 'unknown', 'shamayim'] }, new Set(Object.keys(conceptNodes)));
assert.deepEqual(companion.conceptNodeIds, ['shamayim']);
const packets = createContextPackets(artifact, companion, conceptNodes);
assert.deepEqual(packets.map(packet => packet.packetType), ['interpretive_context', 'explore_context']);
assert.equal(packets[1].content.nodes[0].id, 'shamayim');
assert.equal(createContextPackets(artifact, validateContextCompanion({}, new Set()), conceptNodes).length, 0);
console.log('Bounded context and approved concept selection checks passed.');
