import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { captureQualificationPrompt } from '../api/interpret.js';
import { qualifyReviews } from '../scripts/prism-model-qualification.mjs';
const corpus = JSON.parse(readFileSync(new URL('../evals/model-qualification/corpus.json', import.meta.url)));
assert.equal(corpus.length, 50);
assert.equal(new Set(corpus.map(c => c.id)).size, 50);
assert.equal(corpus.every(c => c.approval === 'unreviewed'), true);
const plain = captureQualificationPrompt({ query: 'What does emet mean?' });
assert.equal(plain.retrievalStatus, 'no-retrieval-smoke-only');
const suffering = captureQualificationPrompt({ query: 'Why does God allow children to suffer?', ragContext: '\nFROZEN_RAG_MARKER', learningContext: '\nFROZEN_LEARNING_MARKER' });
assert.equal(suffering.modules.theodicy, true);
assert.equal(suffering.retrievalStatus, 'caller-supplied-frozen-context');
assert.ok(suffering.system.indexOf('FROZEN_RAG_MARKER') < suffering.system.indexOf('FROZEN_LEARNING_MARKER'));
assert.ok(suffering.system.includes('FROZEN_LEARNING_MARKER'));
assert.throws(() => captureQualificationPrompt({ query: 'x'.repeat(12001) }));
const ids = corpus.map(c => c.id);
const reviews = ids.map(caseId => ({ caseId, fidelity: 4, reasoning: 4, voice: 4, constraints: 4, factualIntegrity: 4, criticalFailures: [], reviewer: 'test fixture', rationale: 'synthetic gate test' }));
assert.equal(qualifyReviews(reviews, ids).offlineQualityGate, true);
assert.equal(qualifyReviews(reviews, ids).productionPromotion, false);
assert.equal(qualifyReviews(reviews.slice(1), ids).offlineQualityGate, false);
const failed = structuredClone(reviews); failed[0].criticalFailures.push('fabricated verse');
assert.equal(qualifyReviews(failed, ids).offlineQualityGate, false);
const below = structuredClone(reviews); below.slice(0,3).forEach(r => r.voice = 3);
assert.equal(qualifyReviews(below, ids).offlineQualityGate, false);
assert.throws(() => qualifyReviews([...reviews, reviews[0]], ids));
console.log('Model qualification: corpus, prompt preparation and fail-closed review gates passed.');
