import assert from 'node:assert/strict';
import {anthropicRequest,anthropicUsage,anthropicAdapter,costFromUsage,reserveCost,SONNET_RATE,SpendLedger} from '../scripts/prism-execution-adapters.mjs';
const snapshot={system:'exact frozen system\n',input:'exact frozen query'};
const body=anthropicRequest(snapshot,3151);
assert.equal(body.system[0].text,snapshot.system);assert.equal(body.messages[0].content,snapshot.input);
assert.equal(body.max_tokens,3151);assert.equal(body.output_config.effort,'low');
assert.equal(body.thinking.type,'adaptive');assert.equal(body.service_tier,'standard_only');
assert.equal(body.system[0].cache_control.ttl,'5m');
const raw={input_tokens:10,cache_read_input_tokens:100,cache_creation_input_tokens:1000,output_tokens:200};
const usage=anthropicUsage(raw);
assert.equal(usage.input_tokens,1110);assert.equal(usage.output_tokens_details.reasoning_tokens,null);
assert.equal(anthropicUsage({...raw,output_tokens_details:{thinking_tokens:50}}).output_tokens_details.reasoning_tokens,50);
assert.throws(()=>anthropicUsage({...raw,output_tokens_details:{thinking_tokens:201}}));
assert.equal(costFromUsage(usage,SONNET_RATE),0.00681);
assert.throws(()=>anthropicUsage({...raw,cache_creation:{ephemeral_1h_input_tokens:10}}));
assert.throws(()=>anthropicUsage({...raw,input_tokens:-1}));
const ledger=new SpendLedger(2);ledger.reserve(0.91693448);
assert.throws(()=>ledger.reserve(1.08306553));
assert.ok(reserveCost(35000,3151,SONNET_RATE)>costFromUsage(usage,SONNET_RATE));
let calls=0;
const adapter=anthropicAdapter('synthetic-test-secret',async(url,options)=>{
 calls++;assert.equal(options.headers['anthropic-version'],'2023-06-01');
 assert.equal(options.headers['x-api-key'],'synthetic-test-secret');
 const sent=JSON.parse(options.body);assert.equal(sent.system[0].text,snapshot.system);
 if(url.endsWith('/count_tokens'))return new Response(JSON.stringify({input_tokens:35000}));
 assert.equal(url,'https://api.anthropic.com/v1/messages');
 return new Response(JSON.stringify({id:'msg-test',model:'claude-sonnet-4-6',content:[{type:'thinking',thinking:'private reasoning'},{type:'text',text:'visible answer'}],usage:{...raw,service_tier:'standard'},stop_reason:'end_turn'}),{headers:{'request-id':'req-test'}});
});
assert.equal((await adapter.count(body)).data.input_tokens,35000);
const result=await adapter.execute(body);assert.equal(result.response,'visible answer');assert.equal(result.status,'completed');
assert.equal(result.requestId,'req-test');assert.equal(calls,2);assert.ok(!JSON.stringify(result).includes('private reasoning'));
const bad=anthropicAdapter('synthetic-test-secret',async()=>new Response(JSON.stringify({error:{type:'authentication_error',message:'synthetic-test-secret'}}),{status:401}));
assert.equal((await bad.execute(body)).error,'authentication_error');assert.ok(!JSON.stringify(await bad.execute(body)).includes('synthetic-test-secret'));
console.log('Sonnet adapter tests passed: exact text, total input accounting, null reasoning count, TTL, prior spend, safe errors and response extraction.');
